"""Validation of the TACHYON RETROBOUND integration against original R1 and paired arms.

Golden fixture is generated by replaying the original standalone Python
R1 on 2026-11-23, BEFORE testing the DemiHead port; this is NOT an external
science benchmark or evidence about late physical entropy.
"""
from __future__ import annotations
import json
import math
from pathlib import Path
import unittest

from tools import tachyon_retrobound_r1 as port
from tools import tachyon_retrobound_r1_paired_validation as paired


GOLDEN = (
    Path(__file__).resolve().parents[1] /
    "research" / "tachyon" / "retrobound_r1_original_golden_fixture_20261123.json"
)


class RetroboundPortParity(unittest.TestCase):
    def test_source_identity_is_frozen_original(self):
        j = json.loads(GOLDEN.read_text(encoding="utf-8"))
        self.assertEqual(j["original_python_sha256"], port.SOURCE_SHA256)
        self.assertEqual(j["original_unittest"]["passed"], 8)
        self.assertEqual(j["original_unittest"]["total"], 8)

    def test_original_r1_golden_numeric_replay(self):
        fixture = json.loads(GOLDEN.read_text(encoding="utf-8"))
        got = port.run_gated(**fixture["config"])
        self.assertTrue(got["all_checks_passed"])
        self.assertAlmostEqual(
            got["theory"]["hidden_early_correlation"],
            fixture["theoretical_hidden_correlation"], places=12
        )
        for arm, source in fixture["arms"].items():
            observed = got["arms"][arm]
            fields = {
                "hidden_past_future_correlation": "hidden_past_future_correlation",
                "future_endpoint_correlation": "future_endpoint_correlation",
                "visible_early_parity_difference": "visible_early_parity_difference_by_b",
                "mean_forward_draws_per_accepted": "forward_draws_per_accepted_path",
            }
            for src_key, new_key in fields.items():
                with self.subTest(arm=arm, field=src_key):
                    self.assertAlmostEqual(source[src_key], observed[new_key], places=12)

    def test_paired_common_late_choice_schedule(self):
        out = paired.paired_validation(
            steps=5, rho=0.65, eta=0.7, trials=2000, seed=20261123
        )
        self.assertTrue(out["checks"]["all_arms_shared_identical_future_choice_schedule"])
        schedule = {x["common_late_choice_schedule_sha256"] for x in out["arms"].values()}
        self.assertEqual(len(schedule), 1)
        choice_counts = {tuple(x["choice_n"].items()) for x in out["arms"].values()}
        self.assertEqual(len(choice_counts), 1)

    def test_paired_postselection_real_cost_and_exact_equivalence(self):
        out = paired.paired_validation(
            steps=5, rho=0.65, eta=0.7, trials=2000, seed=20261123
        )
        self.assertTrue(out["theory"]["two_boundary_equals_postselection_in_exact_path_distribution"])
        self.assertEqual(out["arms"]["causal_null"]["total_forward_draws"], 2000)
        self.assertGreater(out["arms"]["postselection"]["total_forward_draws"], 2000)
        self.assertAlmostEqual(
            out["theory"]["forward_postselection_expected_draws_per_accepted"], 1.7
        )

    def test_physical_verdicts_cannot_be_promoted(self):
        out = paired.paired_validation(
            steps=3, rho=0.5, eta=0.4, trials=1000, seed=20261123
        )
        gate = out["scientific_boundary"]
        self.assertFalse(gate["future_choice_is_independent_physical_late_entropy"])
        self.assertFalse(gate["early_record_was_immutable_and_external_before_late_choice"])
        self.assertFalse(gate["physical_retrocausal_effect_measured"])
        self.assertFalse(gate["postselection_excluded"])
        self.assertTrue(gate["no_signalling_of_public_parity_is_by_construction"])

    def test_invalid_paired_input_fails_closed(self):
        for args in (
            dict(steps=0, trials=1000),
            dict(rho=-1, trials=1000),
            dict(eta=1, trials=1000),
            dict(trials=99),
            dict(seed=-1, trials=1000),
        ):
            with self.subTest(args=args), self.assertRaises(ValueError):
                paired.paired_validation(**args)

    def test_parameter_exact_relation_multiple_cases(self):
        from itertools import product
        for n, rho, eta in product((1, 2, 5), (0.0, 0.4, 0.8), (0.0, 0.6)):
            self.assertAlmostEqual(
                port.hidden_mean(n, rho, eta, 1, 0), eta * rho ** n, places=11
            )
            self.assertLess(port.exact_tv(n, rho, eta, port.accessible_record), 1e-11)


if __name__ == "__main__":
    unittest.main()
