"""TACHYON R3.6 — dimensional symbolic residual formula search.

REAL algorithm, SYNTHETIC instrument-like data. It can find a correction to
an intentionally incomplete Ohm baseline but CANNOT beat the exact generating
law on samples generated by that same law. Real experimental observations are
excluded absent independent rights/curation and a source-family sealed test.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
from datetime import datetime,timezone
from itertools import combinations
import hashlib
import json
import math
from pathlib import Path
import random

SCHEMA="janus.tachyon.r36.symbolic_residual_science_gate.v1"
OUT_SCHEMA="janus.tachyon.r36.symbolic_candidate_research_result.v1"
SEED=20261111
TREF_K=20.0
IREF_A=1.0
TERM_NAMES=("theta","theta_squared","normalized_current",
            "normalized_current_squared","theta_times_normalized_current")
# Five SI dimensions here: mass, length, time, current, temperature.
D0=(0,0,0,0,0)
DA=(0,0,0,1,0)
DOHM=(1,2,-3,-2,0)
DV=(1,2,-3,-1,0)
DK=(0,0,0,0,1)
TOTAL={"train":84,"validation":42,"future_test":54}
EXCLUDED_REAL_LAB={
 "https://zenodo.org/records/15081911",
 "https://zenodo.org/records/13142016"
}
SCENARIOS={
 "TEMPERATURE_DEPENDENT_RESISTOR_SYNTHETIC":0.004,
 "PURE_OHM_SYNTHETIC_NEGATIVE_CONTROL":0.0
}

def need(ok,message):
    if not ok:raise ValueError(message)

def canonical(obj):
    return json.dumps(obj,ensure_ascii=False,sort_keys=True,
                      separators=(",",":"),allow_nan=False).encode("utf8")

def sha(obj):return hashlib.sha256(canonical(obj)).hexdigest()

def dadd(a,b):return tuple(x+y for x,y in zip(a,b))
def dsub(a,b):return tuple(x-y for x,y in zip(a,b))
def dmul(a,n):return tuple(x*n for x in a)

def validate_formula_dimensions(terms):
    """Every candidate term MUST produce volts, no untyped + or extra units."""
    need(dadd(DA,DOHM)==DV and dsub(DK,DK)==D0,
         "R36_SI_BASELINE_DIMENSIONS")
    need(isinstance(terms,tuple) and len(terms)<=2
         and len(set(terms))==len(terms)
         and all(t in TERM_NAMES for t in terms),
         "R36_UNAPPROVED_FORMULA_GRAMMAR")
    dims={
     "theta":dsub(DK,DK),
     "theta_squared":dmul(dsub(DK,DK),2),
     "normalized_current":dsub(DA,DA),
     "normalized_current_squared":dmul(dsub(DA,DA),2),
     "theta_times_normalized_current":dadd(dsub(DK,DK),dsub(DA,DA))
    }
    for term in terms:
        need(dadd(dadd(DA,DOHM),dims[term])==DV,
             "R36_CANDIDATE_DIMENSION_MISMATCH")
    return True

def validate_manifest(m):
    need(m.get("schema")==SCHEMA
         and m.get("research_authorization",None) is None
         and m.get("kind")=="SYNTHETIC_INSTRUMENT_LIKE_SIMULATOR"
         and m.get("scientific_admission")=="HOLD"
         and m.get("production_model_promotion") is False
         and m.get("source_rights_curator_approved_real_lab_data") is False
         and m.get("third_party_blind_assessor_connected") is False
         and m.get("real_measurements_used_for_gradients") is False,
         "R36_NOT_APPROVED_FOR_EXTERNAL_LAB_TRAINING")
    need(m.get("target_dimension_si")=="V"
         and m.get("current_dimension_si")=="A"
         and m.get("resistance_dimension_si")=="Ω"
         and m.get("temperature_difference_unit")=="K"
         and m.get("reference_temperature_difference_kelvin")==TREF_K
         and m.get("reference_current_ampere")==IREF_A,
         "R36_SI_REFERENCE_DRIFT")
    need(m.get("candidate_terms")==list(TERM_NAMES)
         and m.get("maximum_new_terms")==2
         and m.get("train_records")==TOTAL["train"]
         and m.get("validation_records")==TOTAL["validation"]
         and m.get("future_test_records")==TOTAL["future_test"],
         "R36_GRAMMAR_OR_DATASET_DRIFT")
    need({x.get("id"):x.get("truth_coefficient_kelvin_inverse")
          for x in m.get("scenarios",[])}==SCENARIOS,
         "R36_SIMULATOR_SCENARIO_DRIFT")
    release=m.get("release_rule",{})
    need(release.get("minimum_validation_relative_RMSE_reduction")==.20
         and release.get("minimum_future_test_relative_RMSE_reduction")==.15
         and release.get("no_self_generated_training_labels") is True
         and release.get("no_real_laboratory_promotion_without_external_signed_review") is True,
         "R36_AUTOMATIC_PROMOTION_DENIED")
    validate_formula_dimensions(())
    return m

def admit_training_source(source_url,curator_signed=False):
    """Deliberately fail closed; caller cannot forge approval using a bool."""
    if source_url in EXCLUDED_REAL_LAB or source_url!="SYNTHETIC_GENERATOR_ONLY":
        raise ValueError("R36_REAL_LAB_CURATOR_RIGHTS_AND_BLIND_HOLD")
    need(curator_signed is False,
         "R36_SELF_ASSERTED_CURATOR_SIGNATURE_NOT_TRUSTED")
    return True

@dataclass(frozen=True)
class Observation:
    case_id:str
    current_ampere:float
    resistance_ohm:float
    temperature_change_kelvin:float
    observed_voltage:float
    source_kind:str

def validate_observation(row):
    need(isinstance(row,Observation),"R36_BAD_OBSERVATION")
    need(row.source_kind=="SYNTHETIC_GENERATOR_ONLY",
         "R36_UNAPPROVED_OBSERVATION_SOURCE")
    vals=(row.current_ampere,row.resistance_ohm,
          row.temperature_change_kelvin,row.observed_voltage)
    need(all(type(v) in (int,float) and math.isfinite(v) for v in vals),
         "R36_NONFINITE_OBSERVATION")
    need(0<row.current_ampere<=3
         and 0<row.resistance_ohm<100
         and abs(row.temperature_change_kelvin)<=50
         and row.observed_voltage>0,
         "R36_OBSERVATION_DOMAIN")
    return row

def generate_simulator(scenario,split):
    """Created only once per split, never from a model's own predictions."""
    need(scenario in SCENARIOS and split in TOTAL,"R36_UNKNOWN_SCENARIO_OR_SPLIT")
    offset={"train":101,"validation":202,"future_test":303}[split]
    prefix={"TEMPERATURE_DEPENDENT_RESISTOR_SYNTHETIC":1000,
            "PURE_OHM_SYNTHETIC_NEGATIVE_CONTROL":2000}[scenario]
    rng=random.Random(SEED+prefix+offset)
    output=[]
    width=25. if split=="future_test" else 16.
    for i in range(TOTAL[split]):
        current=.25+1.65*rng.random()
        resistance=3.+25.*rng.random()
        temp_delta=(2*rng.random()-1)*width
        base=current*resistance
        # Synthetic "measurement" includes a possible omitted environmental
        # correction plus independent bounded instrument-like noise.
        measured=base*(1+SCENARIOS[scenario]*temp_delta+
                       .001*(2*rng.random()-1))
        output.append(validate_observation(Observation(
            case_id=f"{scenario}_{split}_{i:03d}",
            current_ampere=current,
            resistance_ohm=resistance,
            temperature_change_kelvin=temp_delta,
            observed_voltage=measured,
            source_kind="SYNTHETIC_GENERATOR_ONLY"
        )))
    need(len({r.case_id for r in output})==len(output),"R36_DUPLICATE_ROWS")
    return output

def baseline(row):
    validate_observation(row)
    return row.current_ampere*row.resistance_ohm

def features(row):
    theta=row.temperature_change_kelvin/TREF_K
    j=(row.current_ampere-IREF_A)/IREF_A
    return {
      "theta":theta,
      "theta_squared":theta*theta,
      "normalized_current":j,
      "normalized_current_squared":j*j,
      "theta_times_normalized_current":theta*j,
    }

def solve_linear(mat,vals):
    """Numerically bounded 1- or 2-feature normal equations; no eval/exec."""
    n=len(vals)
    need(0<n<=2 and len(mat)==n and all(len(r)==n for r in mat),
         "R36_LINEAR_DIMENSIONS")
    a=[[float(v) for v in row]+[float(vals[i])]
       for i,row in enumerate(mat)]
    for k in range(n):
        pivot=max(range(k,n),key=lambda i:abs(a[i][k]))
        a[k],a[pivot]=a[pivot],a[k]
        need(abs(a[k][k])>1e-12,"R36_ILL_CONDITIONED_TERMS")
        d=a[k][k]
        for j in range(k,n+1):a[k][j]/=d
        for i in range(n):
            if i==k:continue
            factor=a[i][k]
            for j in range(k,n+1):a[i][j]-=factor*a[k][j]
    return [a[i][-1] for i in range(n)]

def fit_terms(rows,terms):
    validate_formula_dimensions(terms)
    need(rows and all(isinstance(x,Observation) for x in rows),
         "R36_INVALID_FIT_SOURCE")
    if not terms:return ()
    vectors=[];observations=[]
    for row in rows:
        validate_observation(row)
        basis=features(row)
        vectors.append([basis[t] for t in terms])
        observations.append(row.observed_voltage/baseline(row)-1.)
    k=len(terms)
    mat=[[sum(v[i]*v[j] for v in vectors)+(.000001 if i==j else 0.)
          for j in range(k)] for i in range(k)]
    b=[sum(v[i]*z for v,z in zip(vectors,observations))
       for i in range(k)]
    x=solve_linear(mat,b)
    need(all(math.isfinite(v) and abs(v)<1 for v in x),
         "R36_FITTED_CORRECTION_UNPHYSICAL_OR_UNBOUNDED")
    return tuple(x)

def predict(row,terms,coefficients):
    validate_formula_dimensions(terms)
    need(len(terms)==len(coefficients),"R36_FORMULA_COEFFICIENT_COUNT")
    base=baseline(row)
    corr=sum(c*features(row)[term] for term,c in zip(terms,coefficients))
    need(-.5<=corr<=.5,"R36_CORRECTION_EXCEEDS_SANDBOX_SCOPE")
    val=base*(1+corr)
    need(val>0 and math.isfinite(val),"R36_INVALID_PREDICTION")
    return val

def rmse(rows,terms=(),coefs=()):
    err=[(predict(row,terms,coefs)-row.observed_voltage)**2
         for row in rows]
    return math.sqrt(sum(err)/len(err))

def candidates():
    possibilities=[()]
    for size in (1,2):
        possibilities.extend(combinations(TERM_NAMES,size))
    return tuple(possibilities)

def equation(terms,coefficients):
    validate_formula_dimensions(terms)
    strings={
     "theta":"(ΔT/20 K)",
     "theta_squared":"(ΔT/20 K)^2",
     "normalized_current":"((I-1 A)/1 A)",
     "normalized_current_squared":"((I-1 A)/1 A)^2",
     "theta_times_normalized_current":"(ΔT/20 K)*((I-1 A)/1 A)"
    }
    parts=[f"{v:+.9g}*{strings[k]}" for k,v in zip(terms,coefficients)]
    return "V = I*R*(1"+(" "+" ".join(parts) if parts else "")+")"

def frozen_candidate(train,cal):
    baseval=rmse(cal)
    results=[]
    # All 16 grammar shapes are tried exactly once, including baseline.
    for terms in candidates():
        coeffs=fit_terms(train,terms)
        loss=rmse(cal,terms,coeffs)
        # Complexity penalty decided before looking at future test.
        objective=loss+.03*baseval*len(terms)
        results.append({"terms":list(terms),"coefficients":list(coeffs),
                        "validation_rmse":loss,"selection_cost":objective})
    results.sort(key=lambda x:(x["selection_cost"],len(x["terms"]),x["terms"]))
    best=results[0]
    improvement=(baseval-best["validation_rmse"])/baseval if baseval>0 else 0.
    allowed=bool(best["terms"] and improvement>=.20)
    chosen=tuple(best["terms"]) if allowed else ()
    # Fitting on train+validation after structure selection, before heldout.
    coeffs=fit_terms(train+cal,chosen)
    sealed={
       "terms":list(chosen),
       "coefficients":list(coeffs),
       "equation":equation(chosen,coeffs),
       "data_trained_on":"SYNTHETIC_INSTRUMENT_GENERATOR_TRAIN_PLUS_VALIDATION",
       "pre_test_selection_validation_improvement_ratio":improvement,
       "rejected_as_no_material_validation_gain":not allowed,
       "training_case_ids_sha256":sha([r.case_id for r in train]),
       "validation_case_ids_sha256":sha([r.case_id for r in cal]),
       "all_16_candidate_trials":results,
       "source_gradient_authorization":"AUTHOR_SIMULATOR_SANDBOX_ONLY",
       "independent_external_custodian_signature_present":False,
       "scientific_admission":"HOLD",
    }
    sealed["candidate_pre_test_sha256"]=sha(sealed)
    return sealed

def run_one(manifest,scenario):
    validate_manifest(manifest)
    need(scenario in SCENARIOS,"R36_SCENARIO_NOT_ALLOWED")
    train=generate_simulator(scenario,"train")
    cal=generate_simulator(scenario,"validation")
    need(not ({r.case_id for r in train}&{r.case_id for r in cal}),
         "R36_CALIBRATION_LEAK")
    sealed=frozen_candidate(train,cal)
    # Future test values are drawn only AFTER candidate structure and
    # coefficient identity sealed. Public self-authored, not truly blind.
    test=generate_simulator(scenario,"future_test")
    need(not({r.case_id for r in test}&
             {r.case_id for r in train+cal}),"R36_FUTURE_TEST_LEAK")
    terms=tuple(sealed["terms"]);coefs=tuple(sealed["coefficients"])
    old=rmse(test)
    new=rmse(test,terms,coefs)
    gain=(old-new)/old if old>0 else 0.
    sign_aligned=bool(terms and gain>=.15 and new<old)
    # A synthetic positive may be saved as a RESEARCH candidate only; never
    # an accepted physical law or unsupervised source of training gold.
    record={
      "scenario":scenario,
      "scenario_source_class":"AUTHOR_GENERATED_SYNTHETIC_OBSERVATIONS",
      "source_dataset_publication":"NONE",
      "train_count":len(train),"calibration_count":len(cal),
      "future_test_count":len(test),
      "selected_formula":sealed["equation"],
      "candidate_pre_test_sha256":sealed["candidate_pre_test_sha256"],
      "chosen_basis_terms":sealed["terms"],
      "fitted_correction_coefficients":sealed["coefficients"],
      "number_of_all_candidate_structures_tried":len(sealed["all_16_candidate_trials"]),
      "all_candidate_selection_trials":sealed["all_16_candidate_trials"],
      "baseline_ohm_future_test_RMSE_volts":old,
      "candidate_future_test_RMSE_volts":new,
      "future_test_relative_RMSE_improvement":gain,
      "synthetic_independent_future_test_pass":sign_aligned,
      "automatic_research_refit_done":bool(terms),
      "author_public_test_not_independent_blind":True,
      "learned_from_own_predictions":False,
      "new_general_physics_law_discovered":False,
      "training_curated_real_lab_measurements":False,
      "candidate_autopromoted_to_production":False,
      "scientific_admission":"HOLD",
      "test_per_case":[
        {"case_id":x.case_id,"observed_synthetic_voltage":x.observed_voltage,
         "known_formula_baseline_voltage":baseline(x),
         "proposed_formula_voltage":predict(x,terms,coefs)}
        for x in test
      ]
    }
    record["receipt_sha256"]=sha(record)
    return record

def experiment(manifest_path,outdir):
    manifest=json.loads(Path(manifest_path).read_text(encoding="utf8"))
    validate_manifest(manifest)
    output=Path(outdir)
    need(not output.exists() or not any(output.iterdir()),
         "R36_REFUSE_OVERWRITE_EXISTING_EVIDENCE")
    runs=[run_one(manifest,scenario) for scenario in SCENARIOS]
    need(all(z["scientific_admission"]=="HOLD" for z in runs),
         "R36_BAD_SCIENTIFIC_STATUS")
    summary={
        "schema":OUT_SCHEMA,
        "manifest_sha256":sha(manifest),
        "experiment_run_timestamp_utc_untrusted_local_clock":
          datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "scenarios":runs,
        "synthetic_positive_control_detected":runs[0]["synthetic_independent_future_test_pass"],
        "synthetic_negative_control_rejected":not runs[1]["synthetic_independent_future_test_pass"],
        "real_experimental_measured_data_scored":False,
        "independent_sealed_physical_test_scored":False,
        "self_training_only_means_research_coefficient_fit_on_original_simulator_labels":True,
        "self_generated_predictions_used_as_gold":False,
        "automated_neural_knowledge_base_admission":False,
        "source_curator_signature_present":False,
        "scientific_admission":"HOLD",
        "production_promotion":False
    }
    summary["receipt_sha256"]=sha(summary)
    output.mkdir(parents=True,exist_ok=True)
    (output/"r36_symbolic_formula_discovery.json").write_text(
         json.dumps(summary,ensure_ascii=False,sort_keys=True,indent=2)+"\n",
         encoding="utf8")
    return summary

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--manifest",required=True)
    p.add_argument("--outdir",required=True)
    args=p.parse_args()
    out=experiment(args.manifest,args.outdir)
    print(json.dumps({
      "positive_found":out["synthetic_positive_control_detected"],
      "negative_rejected":out["synthetic_negative_control_rejected"],
      "positive_proposed_equation":out["scenarios"][0]["selected_formula"],
      "positive_test_gain":out["scenarios"][0]["future_test_relative_RMSE_improvement"],
      "negative_test_gain":out["scenarios"][1]["future_test_relative_RMSE_improvement"],
      "scientific_admission":"HOLD",
    },sort_keys=True,ensure_ascii=False))

if __name__=="__main__":main()
